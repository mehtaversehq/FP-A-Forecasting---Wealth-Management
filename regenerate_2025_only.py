PUBLIC.mkdir(exist_ok=True);HIDDEN.mkdir(exist_ok=True)
SEG=['Mass Affluent','High Net Worth','Ultra High Net Worth']
PRODS=['Equities','Fixed Income','Managed Portfolios']
CATS=['Employee','Technology','Compliance','Other Operating']
INITIAL_AUM={'Mass Affluent':150_000_000,'High Net Worth':225_000_000,'Ultra High Net Worth':125_000_000}
INITIAL_CLIENTS={'Mass Affluent':850,'High Net Worth':135,'Ultra High Net Worth':15}
WEIGHTS={'Mass Affluent':[.15,.40,.45],'High Net Worth':[.35,.25,.40],'Ultra High Net Worth':[.42,.18,.40]}
FEE_BP={'Equities':75,'Fixed Income':40,'Managed Portfolios':95}
SEG_DISCOUNT={'Mass Affluent':0,'High Net Worth':5,'Ultra High Net Worth':15}
TURNOVER={'Equities':.60,'Fixed Income':.25,'Managed Portfolios':.35}
TRADING_BPS={'Equities':30,'Fixed Income':12,'Managed Portfolios':18}
RMS={'Mass Affluent':['RM01','RM02','RM03','RM04','RM05'],'High Net Worth':['RM06','RM07','RM08'],'Ultra High Net Worth':['RM09','RM10']}

def rnd(x):return round(float(x),2)
def write_csv(path,rows,columns):
 with open(path,'w',newline='',encoding='utf-8-sig') as f:
  w=csv.DictWriter(f,columns);w.writeheader();w.writerows(rows)

def create_year(year,opening_aum,opening_clients,seed,hidden=False):
 rg=random.Random(seed)
 aums=[]; revenue=[]; expenses=[]; client_states=dict(opening_clients)
 aum_states=dict(opening_aum)
 monthly_seg={}
 for month in range(1,13):
  m=f'{year}-{month:02d}'
  # Correlated market shocks to create coherent cross-segment returns.
  if year==2025:
   equity=rg.gauss(.006,.021); fixed=rg.gauss(.0028,.005); managed=.45*equity+.55*fixed+rg.gauss(0,.004)
  returns=[equity,fixed,managed]
  for seg in SEG:
   op=aum_states[seg];opening_count=client_states[seg]
   rate={'Mass Affluent':.011,'High Net Worth':.009,'Ultra High Net Worth':.007}[seg]
   gross_in=op*max(.005,rate+rg.gauss(0,.0029))
   gross_out=op*max(.003,rate*.63+rg.gauss(0,.0023))
   perf=sum(op*WEIGHTS[seg][i]*returns[i] for i in range(3))
   clos=op+gross_in-gross_out+perf
   # Client count generated by movement, subject to reasonable segment size.
   new=rg.choice([1,2,3,4,5,6]) if seg=='Mass Affluent' else (rg.choice([0,0,1,1,2]) if seg=='High Net Worth' else rg.choice([0,0,0,1]))
   exited=rg.choice([0,0,1,1,2,3]) if seg=='Mass Affluent' else (rg.choice([0,0,0,1]) if seg=='High Net Worth' else 0)
   clients=opening_count+new-exited
   aums.append({'month':m,'segment':seg,'opening_aum_aed':rnd(op),'client_inflows_aed':rnd(gross_in),'client_outflows_aed':rnd(gross_out),'market_pnl_aed':rnd(perf),'closing_aum_aed':rnd(clos),'opening_clients':opening_count,'new_clients':new,'exited_clients':exited,'closing_clients':clients})
   monthly_seg[(m,seg)]={'aum_open':op,'aum_close':clos,'inflow':gross_in,'outflow':gross_out,'pnl':perf,'clients':clients}
   for i,prod in enumerate(PRODS):
    op_p=op*WEIGHTS[seg][i]; close_p=op_p+(gross_in-gross_out)*WEIGHTS[seg][i]+op_p*returns[i]
    avg=(op_p+close_p)/2
    fee_bp=FEE_BP[prod]-SEG_DISCOUNT[seg]
    mgmt=avg*fee_bp/10000/12
    tx=avg*TURNOVER[prod]*TRADING_BPS[prod]/10000/12
    revenue.append({'month':m,'segment':seg,'product':prod,'opening_product_aum_aed':rnd(op_p),'closing_product_aum_aed':rnd(close_p),'average_fee_bearing_aum_aed':rnd(avg),'management_fee_rate_bps_annual':fee_bp,'management_fee_aed':rnd(mgmt),'transaction_advisory_fee_aed':rnd(tx),'total_revenue_aed':rnd(mgmt+tx)})
   aum_states[seg]=clos;client_states[seg]=clients
  for cat in CATS:
   base={'Employee':180_000,'Technology':25_000,'Compliance':21_000,'Other Operating':31_000}[cat]
   factor=1+.028*(year-2025)+.03*(month-1)/12
   val=base*factor*(1+rg.gauss(0,.033))
   if year==2025 and month==5 and cat=='Compliance':val+=28_000
   if year==2025 and month==12 and cat=='Employee':val+=31_000
   expenses.append({'month':m,'category':cat,'actual_expense_aed':rnd(val)})
 return aums,revenue,expenses,monthly_seg

def budgets_2025():
 # Independent ex ante budget: deterministic annual asset/flow assumptions, no access to actual outcomes.
 rows=[]; planned={s:INITIAL_AUM[s] for s in SEG}
 for month in range(1,13):
  rev=0
  for seg in SEG:
   op=planned[seg];nnm=op*.0043;market=op*.0030;closing=op+nnm+market
   avg=(op+closing)/2
   for i,prod in enumerate(PRODS):
    asset=avg*WEIGHTS[seg][i]
    bp=FEE_BP[prod]-SEG_DISCOUNT[seg]
    rev+=asset*(bp/10000+TURNOVER[prod]*TRADING_BPS[prod]/10000)/12
   planned[seg]=closing
  planned_exp={cat:{'Employee':178_000,'Technology':24_500,'Compliance':20_500,'Other Operating':30_500}[cat]*(1+.025*(month-1)/12) for cat in CATS}
  total=sum(planned_exp.values())
  rows.append({'month':f'2025-{month:02d}','budget_revenue_aed':rnd(rev),**{f'budget_{c.lower().replace(" ","_")}_aed':rnd(v) for c,v in planned_exp.items()},'budget_total_expenses_aed':rnd(total),'budget_operating_profit_aed':rnd(rev-total)})
 return rows

def rms_2025(aums):
 per=defaultdict(lambda:{'nnm':0,'aum':0,'clients':0})
 for r in aums:
  seg=r['segment'];per[seg]['nnm']+=r['client_inflows_aed']-r['client_outflows_aed']
  if r['month']=='2025-12':per[seg]['aum']=r['closing_aum_aed'];per[seg]['clients']=r['closing_clients']
 rows=[];rndgen=random.Random(928)
 for seg in SEG:
  names=RMS[seg]; weights=[rndgen.uniform(.8,1.2) for _ in names];den=sum(weights)
  def portions(total):
   vals=[rnd(total*w/den) for w in weights];vals[-1]=rnd(total-sum(vals[:-1]));return vals
  a=portions(per[seg]['aum']);n=portions(per[seg]['nnm']);c=[int(per[seg]['clients']*w/den) for w in weights];c[-1]=per[seg]['clients']-sum(c[:-1])
  for i,rm in enumerate(names):rows.append({'rm_id':rm,'primary_segment':seg,'closing_clients_2025':c[i],'closing_aum_2025_aed':a[i],'net_new_money_2025_aed':n[i]})
 return rows

def validations(aums,revenue,expenses,budget,rm):
 t=[]
 def ck(name,condition,detail):t.append({'test':name,'status':'PASS' if condition else 'FAIL','details':detail})
 for year in sorted({r['month'][:4] for r in aums}):
  ar=[r for r in aums if r['month'].startswith(year)]
  rr=[r for r in revenue if r['month'].startswith(year)]
  ee=[r for r in expenses if r['month'].startswith(year)]
  ck(f'{year} row counts',len(ar)==36 and len(rr)==108 and len(ee)==48,'36 AUM /108 product /48 expense')
  for seg in SEG:
   subset=[r for r in ar if r['segment']==seg]
   ck(f'{year} {seg} AUM bridge',all(abs(r['opening_aum_aed']+r['client_inflows_aed']-r['client_outflows_aed']+r['market_pnl_aed']-r['closing_aum_aed'])<.025 for r in subset),'Rounding tolerance AED 0.025')
   ck(f'{year} {seg} roll-forward',all(abs(subset[i]['closing_aum_aed']-subset[i+1]['opening_aum_aed'])<.025 for i in range(11)),'Dec/Jan continuity within year')
   ck(f'{year} {seg} client roll-forward',all(r['opening_clients']+r['new_clients']-r['exited_clients']==r['closing_clients'] for r in subset),'All 12 months')
  for m in range(1,13):
   month=f'{year}-{m:02d}'
   aa=[r for r in ar if r['month']==month];rrr=[r for r in rr if r['month']==month]
   ck(f'{month} product AUM reconciliation',abs(sum(r['closing_product_aum_aed'] for r in rrr)-sum(r['closing_aum_aed'] for r in aa))<.11,'Nine products sum to AUM (AED tolerance 0.11)')
   ck(f'{month} revenue arithmetic',all(abs(r['management_fee_aed']+r['transaction_advisory_fee_aed']-r['total_revenue_aed'])<.025 for r in rrr),'Rounded AED 0.025')
  if year=='2025':
   ck('2025 RM year-end AUM allocation',abs(sum(r['closing_aum_2025_aed'] for r in rm)-sum(r['closing_aum_aed'] for r in ar if r['month']=='2025-12'))<.06,'RM total vs December segment closing AUM')
   ck('2025 RM client coverage',sum(r['closing_clients_2025'] for r in rm)==sum(r['closing_clients'] for r in ar if r['month']=='2025-12'),'RM coverage equals segment closing clients')
   ck('2025 RM net flows',abs(sum(r['net_new_money_2025_aed'] for r in rm)-sum(r['client_inflows_aed']-r['client_outflows_aed'] for r in ar))<.12,'RM NNM equals FY2025 segment NNM')
   ck('2025 budget independence',len(budget)==12 and all(abs(r['budget_total_expenses_aed']+r['budget_operating_profit_aed']-r['budget_revenue_aed'])<.025 for r in budget),'Budget constructed without realized monthly actuals')
 return t

def quarter_summary(aums,revenue,expenses):
 rows=[]
 for q in range(1,5):
  months=[f'2026-{m:02d}' for m in range((q-1)*3+1,q*3+1)]
  aa=[r for r in aums if r['month'] in months];rr=[r for r in revenue if r['month'] in months];ee=[r for r in expenses if r['month'] in months]
  op=sum(r['opening_aum_aed'] for r in aa if r['month']==months[0]);end=sum(r['closing_aum_aed'] for r in aa if r['month']==months[-1])
  nnm=sum(r['client_inflows_aed']-r['client_outflows_aed'] for r in aa);pnl=sum(r['market_pnl_aed'] for r in aa)
  management=sum(r['management_fee_aed'] for r in rr);trans=sum(r['transaction_advisory_fee_aed'] for r in rr);rev=management+trans;exp=sum(r['actual_expense_aed'] for r in ee)
  rows.append({'quarter':f'2026-Q{q}','opening_aum_aed':rnd(op),'net_new_money_aed':rnd(nnm),'market_pnl_aed':rnd(pnl),'closing_aum_aed':rnd(end),'management_fee_aed':rnd(management),'transaction_advisory_fee_aed':rnd(trans),'total_revenue_aed':rnd(rev),'operating_expenses_aed':rnd(exp),'operating_profit_aed':rnd(rev-exp),'cost_to_income_pct':rnd(exp/rev*100)})
 return rows


